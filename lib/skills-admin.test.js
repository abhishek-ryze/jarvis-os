// Self-check: node lib/skills-admin.test.js (temp folder only, never touches ~/.claude)
const assert = require('assert')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { archive, unarchive } = require('./skills-admin')

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'aos-skills-'))
fs.mkdirSync(path.join(root, 'demo'))
fs.writeFileSync(path.join(root, 'demo', 'SKILL.md'), '---\nname: demo\n---\n')

archive(root, 'demo')
assert.ok(!fs.existsSync(path.join(root, 'demo')), 'moved out')
assert.ok(fs.existsSync(path.join(root, '.archive', 'demo', 'SKILL.md')), 'moved into .archive')

fs.mkdirSync(path.join(root, 'demo'))
fs.writeFileSync(path.join(root, 'demo', 'SKILL.md'), 'x')
assert.throws(() => unarchive(root, 'demo'), /target exists/)
fs.rmSync(path.join(root, 'demo'), { recursive: true })

unarchive(root, 'demo')
assert.ok(fs.existsSync(path.join(root, 'demo', 'SKILL.md')), 'moved back')
assert.throws(() => archive(root, '../x'), /bad skill name/)
assert.throws(() => archive(root, 'nope'), /not found/)
fs.rmSync(root, { recursive: true })
console.log('ok: archive, unarchive, guards')

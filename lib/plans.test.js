// Self-check: node lib/plans.test.js
const assert = require('assert')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { listPlans } = require('./routes-sessions')

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'aos-plans-'))
fs.writeFileSync(path.join(dir, 'old.md'), 'intro\n# Old plan\nbody')
fs.writeFileSync(path.join(dir, 'new.md'), '## Second heading\r\nbody')
fs.writeFileSync(path.join(dir, 'none.md'), 'no heading here')
fs.writeFileSync(path.join(dir, 'skip.txt'), '# not md')
fs.utimesSync(path.join(dir, 'old.md'), 1, 1)
const r = listPlans(dir)
assert.deepStrictEqual(r.map(p => p.name).sort(), ['new.md', 'none.md', 'old.md'])
assert.strictEqual(r[r.length - 1].name, 'old.md', 'newest first')
assert.strictEqual(r.find(p => p.name === 'old.md').heading, 'Old plan')
assert.strictEqual(r.find(p => p.name === 'new.md').heading, 'Second heading')
assert.strictEqual(r.find(p => p.name === 'none.md').heading, '')
assert.ok(r[0].size > 0 && r[0].mtime > 0 && path.isAbsolute(r[0].path))
assert.deepStrictEqual(listPlans(path.join(dir, 'missing')), [])
fs.rmSync(dir, { recursive: true })
console.log('plans ok')

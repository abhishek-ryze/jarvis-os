// Self-check: node lib/microapps.test.js
const assert = require('assert')
const fs = require('fs')
const os = require('os')
const path = require('path')
const m = require('./microapps')

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'aos-mapp-'))
const dir = path.join(root, 'apps'), other = path.join(root, 'other')
fs.mkdirSync(path.join(dir, 'sub'), { recursive: true }); fs.mkdirSync(other)
fs.writeFileSync(path.join(dir, 'zz-calc.html'), '<title>Calc Pro</title><meta name="description" content="Adds numbers">')
fs.writeFileSync(path.join(dir, 'zz-plain.html'), '<meta content=\'Other order\' name=\'description\'>')
fs.writeFileSync(path.join(dir, 'x.js'), 'no')
fs.writeFileSync(path.join(dir, 'sub', 'deep.html'), 'deep')
fs.writeFileSync(path.join(other, 'secret.html'), 'secret')
try {
  const cfg = { microAppDirs: [dir] }
  const apps = m.list(cfg).filter(a => a.file.startsWith('zz-') || ['deep.html', 'x.js'].includes(a.file))
  assert.deepStrictEqual(apps.map(a => a.file), ['zz-calc.html', 'zz-plain.html'], 'html only, no subfolders')
  assert.strictEqual(apps[0].name, 'Calc Pro')
  assert.strictEqual(apps[0].desc, 'Adds numbers')
  assert.strictEqual(apps[0].glyph, 'C')
  assert.strictEqual(apps[1].desc, 'Other order')
  assert.ok(m.resolve(cfg, 'zz-calc.html').endsWith('zz-calc.html'))
  for (const bad of ['../other/secret.html', '..\\other\\secret.html', 'sub/deep.html', 'x.js', 'secret.html', '', null, '.hidden.html', 'zz-calc.html/..', 'C:\\x.html'])
    assert.strictEqual(m.resolve(cfg, bad), null, 'refused: ' + bad)
  assert.ok(!m.addPrompt('x').includes('\u2014'), 'no em dash in prompt')
  assert.ok(m.addPrompt('make a timer').includes('make a timer'))
  console.log('ok: microapps')
} finally { fs.rmSync(root, { recursive: true, force: true }) }
